func pgIdent(s string) string             { return `"` + strings.ReplaceAll(s, `"`, `""`) + `"` }
func pgTable(schema, table string) string { return pgIdent(schema) + "." + pgIdent(table) }

// Conversion and activation share one transaction; old tables remain a backup.
func convertLegacyPostgres(conn *sql.DB) error {
	ctx := context.Background()
	tx, err := conn.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	if _, err = tx.Exec(`SELECT pg_advisory_xact_lock(741905108)`); err != nil {
		return err
	}
	var source string
	if err = tx.QueryRow(`SELECT current_schema()`).Scan(&source); err != nil {
		return err
	}
	var marker, legacy bool
	if err = tx.QueryRow(`SELECT EXISTS(SELECT 1 FROM information_schema.tables WHERE table_schema=? AND table_name='julius_schema_version'), EXISTS(SELECT 1 FROM information_schema.tables WHERE table_schema=? AND table_name<>'goose_db_version')`, source, source).Scan(&marker, &legacy); err != nil {
		return err
	}
	if marker || !legacy {
		return tx.Commit()
	}
	var version int
	if err = tx.QueryRow(`SELECT COALESCE(MAX(version_id),0) FROM ` + pgTable(source, "goose_db_version") + ` WHERE is_applied`).Scan(&version); err != nil {
		return fmt.Errorf("inspect legacy Postgres history: %w", err)
	}
	if version != 46 {
		return fmt.Errorf("unsupported legacy database schema: automatic Postgres conversion requires final legacy version 46, found %d", version)
	}
	suffix := strings.ReplaceAll(uuid.NewString(), "-", "")
	target, backup := "julius_convert_"+suffix, "julius_legacy_"+suffix
	for _, s := range []string{target, backup} {
		if _, err = tx.Exec(`CREATE SCHEMA ` + pgIdent(s)); err != nil {
			return err
		}
	}
	sourceTables, err := pgTables(tx, source)
	if err != nil {
		return err
	}
	// Lock all source tables before reading so the retained snapshot is consistent.
	for _, table := range sourceTables {
		if _, err = tx.Exec(`LOCK TABLE ` + pgTable(source, table) + ` IN ACCESS EXCLUSIVE MODE`); err != nil {
			return err
		}
	}
	if _, err = tx.Exec(`SELECT set_config('search_path', ?, true), set_config('TimeZone','UTC',true)`, pgIdent(target)); err != nil {
		return err
	}
	ddl, err := postgresMigrationsFS.ReadFile("migrations/postgres/0001_initial.sql")
	if err != nil {
		return err
	}
	up := strings.Split(string(ddl), "-- +goose Down")[0]
	if _, err = tx.Exec(up); err != nil {
		return fmt.Errorf("create conversion baseline: %w", err)
	}
	tables, err := pgTables(tx, target)
	if err != nil {
		return err
	}
	// Topological order from the freshly created baseline's foreign keys.
	deps := map[string][]string{}
	rows, err := tx.Query(`SELECT a.relname,b.relname FROM pg_constraint c JOIN pg_class a ON a.oid=c.conrelid JOIN pg_class b ON b.oid=c.confrelid JOIN pg_namespace n ON n.oid=a.relnamespace WHERE c.contype='f' AND n.nspname=? AND a.oid<>b.oid`, target)
	if err != nil {
		return err
	}
	for rows.Next() {
		var a, b string
		if err = rows.Scan(&a, &b); err != nil {
			rows.Close()
			return err
		}
		deps[a] = append(deps[a], b)
	}
	err = rows.Err()
	rows.Close()
	if err != nil {
		return err
	}
	var ordered []string
	seen := map[string]int{}
	var visit func(string) error
	visit = func(table string) error {
		if seen[table] == 1 {
			return fmt.Errorf("baseline FK cycle at %s", table)
		}
		if seen[table] == 2 {
			return nil
		}
		seen[table] = 1
		for _, dep := range deps[table] {
			if err := visit(dep); err != nil {
				return err
			}
		}
		seen[table] = 2
		ordered = append(ordered, table)
		return nil
	}
	expected := map[string]bool{"goose_db_version": true}
	for _, table := range tables {
		expected[table] = true
		if err = visit(table); err != nil {
			return err
		}
	}
	for _, table := range sourceTables {
		if !expected[table] {
			return fmt.Errorf("unmapped legacy Postgres table %s", table)
		}
	}
	for _, table := range ordered {
		if table == "julius_schema_version" {
			continue
		}
		if err = copyLegacyPostgresTable(tx, source, target, table); err != nil {
			return err
		}
	}
	if _, err = tx.Exec(`CREATE TABLE goose_db_version (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,version_id BIGINT NOT NULL,is_applied BOOLEAN NOT NULL,tstamp TIMESTAMP NOT NULL DEFAULT now()); INSERT INTO goose_db_version(version_id,is_applied) VALUES(0,TRUE),(1,TRUE)`); err != nil {
		return err
	}
	// Move old objects away and activate converted objects without changing the DSN.
	for _, table := range sourceTables {
		if _, err = tx.Exec(`ALTER TABLE ` + pgTable(source, table) + ` SET SCHEMA ` + pgIdent(backup)); err != nil {
			return err
		}
	}
	var oldFunction bool
	if err = tx.QueryRow(`SELECT EXISTS(SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace WHERE n.nspname=? AND p.proname='reject_append_only_write')`, source).Scan(&oldFunction); err != nil {
		return err
	}
	if oldFunction {
		if _, err = tx.Exec(`ALTER FUNCTION ` + pgTable(source, "reject_append_only_write") + `() SET SCHEMA ` + pgIdent(backup)); err != nil {
			return err
		}
	}
	tables = append(tables, "goose_db_version")
	for _, table := range tables {
		if _, err = tx.Exec(`ALTER TABLE ` + pgTable(target, table) + ` SET SCHEMA ` + pgIdent(source)); err != nil {
			return err
		}
	}
	if _, err = tx.Exec(`ALTER FUNCTION ` + pgTable(target, "reject_append_only_write") + `() SET SCHEMA ` + pgIdent(source)); err != nil {
		return err
	}
	if _, err = tx.Exec(`DROP SCHEMA ` + pgIdent(target)); err != nil {
		return err
	}
	if err = tx.Commit(); err != nil {
		return err
	}
	log.Printf("legacy Postgres conversion complete; generation 1 active; original schema retained in %s", backup)
	return nil
}

func pgTables(tx *sql.Tx, schema string) ([]string, error) {
	rows, err := tx.Query(`SELECT tablename FROM pg_tables WHERE schemaname=? ORDER BY tablename`, schema)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var tables []string
	for rows.Next() {
		var table string
		if err = rows.Scan(&table); err != nil {
			return nil, err
		}
		tables = append(tables, table)
	}
	return tables, rows.Err()
}

func copyLegacyPostgresTable(tx *sql.Tx, source, target, table string) error {
	rows, err := tx.Query(`SELECT column_name,data_type FROM information_schema.columns WHERE table_schema=? AND table_name=? ORDER BY ordinal_position`, target, table)
	if err != nil {
		return err
	}
	var columns, exprs []string
	known := map[string]bool{}
	for rows.Next() {
		var col, kind string
		if err = rows.Scan(&col, &kind); err != nil {
			rows.Close()
			return err
		}
		known[col] = true
		columns = append(columns, pgIdent(col))
		exprs = append(exprs, legacyPostgresExpr(table, col, kind))
	}
	err = rows.Err()
	rows.Close()
	if err != nil {
		return err
	}
	rows, err = tx.Query(`SELECT column_name FROM information_schema.columns WHERE table_schema=? AND table_name=?`, source, table)
	if err != nil {
		return err
	}
	var found []string
	for rows.Next() {
		var col string
		if err = rows.Scan(&col); err != nil {
			rows.Close()
			return err
		}
		if !known[col] {
			rows.Close()
			return fmt.Errorf("unmapped legacy column %s.%s", table, col)
		}
		found = append(found, col)
	}
	err = rows.Err()
	rows.Close()
	if err != nil {
		return err
	}
	if len(found) != len(columns) {
		return fmt.Errorf("legacy table %s differs from final schema", table)
	}
	if table == "categories" {
		if _, err = tx.Exec(`DELETE FROM ` + pgTable(target, table)); err != nil {
			return err
		}
	}
	selectSQL := `SELECT ` + strings.Join(exprs, ",") + ` FROM ` + pgTable(source, table)
	result, err := tx.Exec(`INSERT INTO ` + pgTable(target, table) + ` (` + strings.Join(columns, ",") + `) ` + selectSQL)
	if err != nil {
		return fmt.Errorf("convert legacy table %s: %w", table, err)
	}
	var count int64
	if err = tx.QueryRow(`SELECT count(*) FROM ` + pgTable(source, table)).Scan(&count); err != nil {
		return err
	}
	copied, err := result.RowsAffected()
	if err != nil {
		return err
	}
	if copied != count {
		return fmt.Errorf("%s row count mismatch", table)
	}
	var different bool
	if err = tx.QueryRow(`SELECT EXISTS((` + selectSQL + `) EXCEPT ALL (SELECT ` + strings.Join(columns, ",") + ` FROM ` + pgTable(target, table) + `))`).Scan(&different); err != nil {
		return err
	}
	if different {
		return fmt.Errorf("%s converted data mismatch", table)
	}
	return nil
}

func legacyPostgresExpr(table, col, kind string) string {
	c := pgIdent(col)
	key := table + "." + col
	switch kind {
	case "uuid":
		return c + "::uuid"
	case "numeric":
		return c + "::numeric"
	case "boolean":
		return c + "::text::boolean"
	case "timestamp with time zone":
		if table == "auth_owner" || table == "auth_sessions" {
			return `TIMESTAMPTZ 'epoch' + ` + c + ` * INTERVAL '1 second'`
		}
		return c + "::timestamptz"
	case "date":
		// Preserve calendar boundaries before Postgres rounds nanoseconds.
		stamp := "regexp_replace(" + c + `::text, '([.][0-9]{6})[0-9]+', '\1')::timestamptz`
		switch key {
		case "financial_accounts.balance_close_date", "financial_accounts.balance_due_date", "financial_bills.due_date", "financial_bills.closing_date":
			return "(" + stamp + " AT TIME ZONE 'UTC')::date"
		case "financial_investments.due_date", "financial_investments.issue_date", "financial_investments.purchase_date":
			return "(" + stamp + " AT TIME ZONE 'Etc/GMT+3')::date"
		case "financial_investment_transactions.trade_date":
			return "CASE WHEN (" + stamp + " AT TIME ZONE 'UTC')::time = TIME '00:00:00' AND " + c + "::text !~ '[.][0-9]*[1-9][0-9]*' THEN (" + stamp + " AT TIME ZONE 'UTC')::date ELSE (" + stamp + " AT TIME ZONE 'Etc/GMT+3')::date END"
		}
		return c + "::date"
	}
	return c
}
