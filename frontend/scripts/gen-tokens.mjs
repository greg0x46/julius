// Generates src/styles/tokens.css and src/theme/tokens.ts from src/theme/tokens.json.
// Usage: node scripts/gen-tokens.mjs [--check]   (--check fails if files are stale)
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("..", import.meta.url);
const src = new URL("src/theme/tokens.json", root);
const outCss = new URL("src/styles/tokens.css", root);
const outTs = new URL("src/theme/tokens.ts", root);
const tokens = JSON.parse(readFileSync(src, "utf8"));

const HEADER = "generated by scripts/gen-tokens.mjs from src/theme/tokens.json — do not edit";

const colorEntries = Object.entries(tokens.colors);
const decl = (name, value) => `  ${name}: ${value};`;

function renderCss() {
  const light = [
    ...colorEntries.map(([, c]) => decl(c.var, c.light)),
    ...Object.values(tokens.radius).map((r) => decl(r.var, r.value)),
    ...Object.values(tokens.type).map((t) => decl(t.var, t.value)),
  ];
  const dark = colorEntries.map(([, c]) => decl(c.var, c.dark ?? c.light));
  const indent = dark.map((l) => "  " + l);
  return `/* ${HEADER} */

:root {
${light.join("\n")}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${indent.join("\n")}
  }
}

:root[data-theme="dark"] {
${dark.join("\n")}
}
`;
}

function renderTs() {
  const colors = colorEntries.map(([k, c]) => `  ${k}: ${JSON.stringify(c.light)},`).join("\n");
  const vars = colorEntries.map(([k, c]) => `  ${k}: ${JSON.stringify(`var(${c.var})`)},`).join("\n");
  const spacing = Object.entries(tokens.spacing)
    .map(([k, v]) => `  ${k}: ${v},`)
    .join("\n");
  const radius = Object.entries(tokens.radius)
    .map(([k, r]) => `  ${k}: ${parseFloat(r.value)},`)
    .join("\n");
  const type = Object.entries(tokens.type)
    .map(([k, t]) => `  ${k}: ${JSON.stringify(t.value)},`)
    .join("\n");
  return `// ${HEADER}

/** Light-theme color values (what antd's ConfigProvider consumes). */
export const colors = {
${colors}
} as const;

/** The same roles as CSS custom-property references, theme-aware. */
export const colorVars = {
${vars}
} as const;

export const fontFamily = ${JSON.stringify(tokens.fontFamily)};

/** 4px baseline spacing scale, for use outside antd's own Space/Flex props. */
export const spacing = {
${spacing}
} as const;

/** Border radii in px. */
export const radius = {
${radius}
} as const;

/** Type scale in rem. */
export const fontSize = {
${type}
} as const;
`;
}

const outputs = [
  [outCss, renderCss()],
  [outTs, renderTs()],
];

if (process.argv.includes("--check")) {
  const stale = outputs.filter(([url, text]) => {
    try {
      return readFileSync(url, "utf8") !== text;
    } catch {
      return true;
    }
  });
  if (stale.length) {
    console.error(
      `Stale generated tokens: ${stale.map(([u]) => fileURLToPath(u)).join(", ")}\nRun: npm run gen:tokens`,
    );
    process.exit(1);
  }
} else {
  for (const [url, text] of outputs) writeFileSync(url, text);
}
